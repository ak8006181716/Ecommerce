const seedProducts = async (req, res) => {
  try {
    // By default, clear old dollar products to replace with realistic INR products
    const { clearExisting = "true" } = req.query;

    if (clearExisting !== "false") {
      await Product.deleteMany({});
    }

    // Process all items concurrently for fast execution
    const seedPromises = sampleProducts.map(async (item) => {
      let cloudinaryImageUrl = item.imageUrl;

      try {
        const uploadRes = await imageUploadUtil(item.imageUrl);
        if (uploadRes && uploadRes.secure_url) {
          cloudinaryImageUrl = uploadRes.secure_url;
        }
      } catch (err) {
        console.log("Cloudinary fallback to raw image URL for:", item.title);
      }

      const product = new Product({
        title: item.title,
        description: item.description,
        category: item.category,
        brand: item.brand,
        price: item.price,
        salePrice: item.salePrice,
        totalStock: item.totalStock,
        averageReview: item.averageReview,
        image: cloudinaryImageUrl,
      });

      return await product.save();
    });

    const seededProducts = await Promise.all(seedPromises);

    res.status(200).json({
      success: true,
      count: seededProducts.length,
      message: `Successfully seeded ${seededProducts.length} products with realistic INR pricing to MongoDB!`,
      data: seededProducts,
    });
  } catch (error) {
    console.error("Seed error:", error);
    res.status(500).json({
      success: false,
      message: error.message || "Failed to seed products",
    });
  }
};

module.exports = { seedProducts };
